use crate::bitmap::Gray;

/// Width in pixels of `text` drawn at `scale`, including inter-character gaps.
pub fn text_width(text: &str, scale: usize) -> usize {
    let n = text.chars().count();
    if n == 0 {
        0
    } else {
        (n * (W + 1) - 1) * scale
    }
}

pub fn line_height(scale: usize) -> usize {
    (H + 2) * scale
}

/// Draw `text` with its top-left at (x, y) in pixels. Returns the x after it.
pub fn draw(img: &mut Gray, x: usize, y: usize, scale: usize, text: &str) -> usize {
    let mut cx = x;
    for ch in text.chars() {
        let c = ch as u32;
        let g = if (FIRST as u32..FIRST as u32 + 95).contains(&c) {
            &GLYPHS[(c - FIRST as u32) as usize]
        } else {
            &GLYPHS[0]
        };
        for (ry, row) in g.iter().enumerate() {
            for rx in 0..W {
                if row >> (W - 1 - rx) & 1 == 0 {
                    continue;
                }
                for sy in 0..scale {
                    let py = y + ry * scale + sy;
                    if py >= img.h {
                        continue;
                    }
                    for sx in 0..scale {
                        let px = cx + rx * scale + sx;
                        if px < img.w {
                            img.set(px, py, 0);
                        }
                    }
                }
            }
        }
        cx += (W + 1) * scale;
    }
    cx
}

/// Break `text` into lines that fit `max_px`, splitting on spaces where possible.
pub fn wrap(text: &str, scale: usize, max_px: usize) -> Vec<String> {
    let per = (W + 1) * scale;
    let cols = (max_px / per).max(1);
    let mut out = Vec::new();
    for para in text.split('\n') {
        if para.is_empty() {
            out.push(String::new());
            continue;
        }
        let mut line = String::new();
        for word in para.split(' ') {
            if line.is_empty() {
                line = word.to_string();
            } else if line.chars().count() + 1 + word.chars().count() <= cols {
                line.push(' ');
                line.push_str(word);
            } else {
                out.push(std::mem::take(&mut line));
                line = word.to_string();
            }
        }
        out.push(line);
    }
    out
}
